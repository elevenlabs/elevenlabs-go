package client

import (
	context "context"
	knowledgebase "github.com/elevenlabs/elevenlabs-go/agents/knowledgebase"
	chunk "github.com/elevenlabs/elevenlabs-go/agents/knowledgebase/documents/chunk"
	chunks "github.com/elevenlabs/elevenlabs-go/agents/knowledgebase/documents/chunks"
	summaries "github.com/elevenlabs/elevenlabs-go/agents/knowledgebase/documents/summaries"
	core "github.com/elevenlabs/elevenlabs-go/core"
	internal "github.com/elevenlabs/elevenlabs-go/internal"
	option "github.com/elevenlabs/elevenlabs-go/option"
	types "github.com/elevenlabs/elevenlabs-go/types"
)

type Client struct {
	WithRawResponse *RawClient

	Summaries *summaries.Client
	Chunk     *chunk.Client
	Chunks    *chunks.Client

	options *core.RequestOptions
	baseURL string
	caller  *internal.Caller
}

func NewClient(options *core.RequestOptions) *Client {
	return &Client{
		WithRawResponse: NewRawClient(options),
		Summaries:       summaries.NewClient(options),
		Chunk:           chunk.NewClient(options),
		Chunks:          chunks.NewClient(options),
		options:         options,
		baseURL:         options.BaseURL,
		caller: internal.NewCaller(
			&internal.CallerParams{
				Client:         options.HTTPClient,
				MaxAttempts:    options.MaxAttempts,
				DisableRetries: options.DisableRetries,
			},
		),
	}
}

// Create a knowledge base document generated by scraping the given webpage.
func (c *Client) CreateFromUrl(ctx context.Context, request *knowledgebase.BodyCreateUrlDocumentV1ConvaiKnowledgeBaseUrlPost, opts ...option.RequestOption) (*types.AddKnowledgeBaseResponseModel, error) {
	response, err := c.WithRawResponse.CreateFromUrl(ctx, request, opts...)
	if err != nil {
		return nil, err
	}
	return response.Body, nil
}

